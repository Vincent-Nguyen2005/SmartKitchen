import React, { useEffect, useRef, useState } from "react";
import { ActivityIndicator, RefreshControl, ScrollView, StyleSheet, Text, View } from "react-native";
import { CookingPot, Search } from "lucide-react-native";
import { AppText, colors, spacing, textStyles } from "../../theme";
import { useSession } from "../../services/session";
import { createGatewayClient, errorMessage } from "../notifications/gatewayApi";
import { EmptyState } from "../notifications/ui";
import { ProductImage } from "../shopping-cart/MarketProducts";
import { SEARCH_CONTENT_GAP, SearchBar } from "../../components/SearchBar";
import { CardCaption, cardImageStyle, ImagePlaceholder, ProductCard, useCardGrid } from "../../components/ProductCard";
import { dayKey, type MealType } from "../menu/MenuCalendar";
import { autoGenerated, generateDay, mealLabels, MenuDishCard, ownDayMenu, sortItems, type MenuItem, type MenuRecord } from "../menu/menuShared";
import { AI_DISCLAIMER, AiDishDetail, loadSavedAiDishes, type AiDish } from "./AiSuggestions";
import CookingMode from "./CookingMode";
import RecipeDetail from "./RecipeDetail";
import { minutesText, totalMinutes, type Recipe } from "./recipeTypes";

type Props = Readonly<{ accessToken: string | null }>;
const DAY_MEALS: MealType[] = ["BREAKFAST", "LUNCH", "DINNER"];

/**
 * "Nấu ăn": today's menu from Lịch (Bữa sáng, Bữa trưa, Bữa tối, same dishes and order), loaded each time the tab
 * opens so it always matches Lịch. With no menu for today yet, it is generated (same rule as Lịch). Typing in the
 * search box searches every active dish (catalog + the family's saved AI dishes) to cook something else.
 */
export default function RecipeScreen({ accessToken }: Props): React.JSX.Element {
  const { family } = useSession();
  const familyId = family?.id ?? null;
  const cardGrid = useCardGrid();
  const horizontalPadding = cardGrid.layout.width < 360 ? spacing.lg : spacing.xl;
  const [menu, setMenu] = useState<MenuRecord | null>(null);
  const [recipes, setRecipes] = useState<Recipe[]>([]);
  const [savedAi, setSavedAi] = useState<AiDish[]>([]);
  const [search, setSearch] = useState("");
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState("");
  const [detail, setDetail] = useState<Recipe | null>(null);
  const [aiDetail, setAiDetail] = useState<{ dish: AiDish; saved: boolean } | null>(null);
  const [cooking, setCooking] = useState<Recipe | null>(null);
  const loadId = useRef(0);
  const api = createGatewayClient(accessToken);
  const todayKey = dayKey(new Date());

  /** Today's menu (generated once when missing), the active recipes and the saved AI dishes. */
  const load = async (): Promise<void> => {
    if (!accessToken) { setLoading(false); return; }
    const id = ++loadId.current;
    setLoading(true);
    setError("");
    try {
      const [menus, list] = await Promise.all([
        api.get<MenuRecord[]>(`/api/menu?from=${todayKey}&to=${todayKey}`),
        api.get<Recipe[]>("/api/recipes?active=true").catch(() => [] as Recipe[]),
      ]);
      if (id !== loadId.current) return;
      setRecipes(Array.isArray(list) ? list : []);
      let today = ownDayMenu(Array.isArray(menus) ? menus : [], todayKey);
      const key = `${familyId ?? "no-family"}:${todayKey}`;
      if (!today && !autoGenerated.has(key)) {
        autoGenerated.add(key);
        setGenerating(true);
        today = await generateDay(api, todayKey, familyId).finally(() => setGenerating(false));
      }
      if (id === loadId.current) setMenu(today);
    } catch (requestError) {
      if (id === loadId.current) setError(errorMessage(requestError));
    } finally {
      if (id === loadId.current) setLoading(false);
    }
    if (familyId) loadSavedAiDishes(api, familyId).then(setSavedAi).catch(() => setSavedAi([]));
  };

  useEffect(() => {
    void load();
  }, [accessToken, familyId]);

  const recipeById = new Map(recipes.map((recipe) => [recipe.id, recipe]));
  const items = menu ? sortItems(menu.items) : [];
  const term = search.trim().toLocaleLowerCase("vi");
  const matches = (name: string, extra: string[]) => `${name} ${extra.join(" ")}`.toLocaleLowerCase("vi").includes(term);
  const recipeResults = term ? recipes.filter((recipe) => matches(recipe.name, [recipe.description ?? "", ...recipe.ingredients])) : [];
  const aiResults = term ? savedAi.filter((dish) => matches(dish.name, [dish.description, ...dish.ingredients.map((ingredient) => ingredient.name)])) : [];
  const anyAiVisible = term ? aiResults.length > 0 : items.some((item) => item.details?.ai);

  const openItem = (item: MenuItem) => {
    if (item.details?.ai && item.details.aiDish) { setAiDetail({ dish: item.details.aiDish, saved: false }); return; }
    const recipe = item.recipeId ? recipeById.get(item.recipeId) : undefined;
    if (recipe) { setDetail(recipe); return; }
    if (item.recipeId) api.get<Recipe>(`/api/recipes/${encodeURIComponent(item.recipeId)}`).then(setDetail).catch((requestError) => setError(errorMessage(requestError)));
  };

  let content: React.ReactNode;
  if ((loading || generating) && !menu && !term) {
    content = (
      <View style={styles.loading}>
        <ActivityIndicator color={colors.primary} />
        <AppText variant="bodySmall" color={colors.muted}>{generating ? "Đang chuẩn bị thực đơn hôm nay" : "Đang tải"}</AppText>
      </View>
    );
  } else if (term) {
    content = recipeResults.length + aiResults.length === 0 ? (
      <EmptyState fill icon={Search} text="Không tìm thấy món ăn phù hợp." />
    ) : (
      <View style={styles.section}>
        <Text style={styles.sectionTitle} accessibilityRole="header">Kết quả tìm kiếm</Text>
        <View onLayout={cardGrid.onLayout} style={[styles.grid, { gap: cardGrid.gap }]}>
          {recipeResults.map((recipe) => {
            const minutes = totalMinutes(recipe);
            const timeText = minutes !== null ? minutesText(minutes) : "Thời gian linh hoạt";
            return (
              <ProductCard
                key={`recipe-${recipe.id}`}
                width={cardGrid.cardWidth}
                accessibilityLabel={`${recipe.name}, ${timeText}. Mở công thức`}
                onPress={() => setDetail(recipe)}
                image={<ProductImage uri={recipe.imageUrl} style={cardImageStyle} />}
                name={recipe.name}
                subtitle={timeText}
                footer={recipe.servings ? <CardCaption text={`${recipe.servings} phần`} /> : undefined}
              />
            );
          })}
          {aiResults.map((dish) => (
            <ProductCard
              key={`ai-${dish.id}`}
              width={cardGrid.cardWidth}
              accessibilityLabel={`Món AI đã lưu: ${dish.name}, ${minutesText(dish.totalMinutes)}. Mở công thức`}
              onPress={() => setAiDetail({ dish, saved: true })}
              image={<ImagePlaceholder />}
              pill={{ label: "AI", tone: "ai" }}
              name={dish.name}
              subtitle={minutesText(dish.totalMinutes)}
              footer={<CardCaption text={`${dish.servings} phần`} />}
            />
          ))}
        </View>
      </View>
    );
  } else if (items.length === 0) {
    content = <EmptyState fill icon={CookingPot} text={error ? "Không tải được thực đơn hôm nay." : "Hôm nay chưa có thực đơn. Mở tab Lịch để tạo."} />;
  } else {
    content = DAY_MEALS.map((meal) => {
      const mealItems = items.filter((item) => item.mealType === meal);
      if (mealItems.length === 0) return null;
      return (
        <View key={meal} style={styles.section}>
          <Text style={styles.sectionTitle} accessibilityRole="header">{mealLabels[meal]}</Text>
          <View onLayout={cardGrid.onLayout} style={[styles.grid, { gap: cardGrid.gap }]}>
            {mealItems.map((item) => (
              <MenuDishCard key={item.id} item={item} recipe={item.recipeId ? recipeById.get(item.recipeId) : undefined} width={cardGrid.cardWidth} onPress={() => openItem(item)} />
            ))}
          </View>
        </View>
      );
    });
  }

  return (
    <View style={styles.screen}>
      <View style={[styles.searchHeader, { paddingHorizontal: horizontalPadding }]}>
        <SearchBar accessibilityLabel="Tìm món ăn" placeholder="Tìm món khác để nấu" value={search} onChangeText={setSearch} />
      </View>
      <ScrollView showsVerticalScrollIndicator={false} showsHorizontalScrollIndicator={false}
        contentContainerStyle={[styles.content, { paddingHorizontal: horizontalPadding }, styles.fill]}
        keyboardShouldPersistTaps="handled"
        refreshControl={<RefreshControl refreshing={loading && !!menu} onRefresh={() => void load()} tintColor={colors.primary} />}
      >
        {!!error && <AppText accessibilityRole="alert" variant="bodySmall" color={colors.danger}>{error}</AppText>}
        {anyAiVisible && <Text style={styles.disclaimer}>{AI_DISCLAIMER}</Text>}
        {content}
      </ScrollView>
      <RecipeDetail recipe={detail} onClose={() => setDetail(null)} onStartCooking={(recipe) => { setDetail(null); setCooking(recipe); }} />
      <AiDishDetail
        dish={aiDetail?.dish ?? null}
        isSaved={aiDetail?.saved ?? false}
        onClose={() => setAiDetail(null)}
        onStartCooking={(recipe) => { setAiDetail(null); setCooking(recipe); }}
        onSaved={() => { if (familyId) loadSavedAiDishes(api, familyId).then(setSavedAi).catch(() => undefined); }}
      />
      <CookingMode recipe={cooking} onClose={() => setCooking(null)} />
    </View>
  );
}

const styles = StyleSheet.create({
  screen: { backgroundColor: colors.background, flex: 1 },
  searchHeader: { paddingTop: spacing.xl, width: "100%" },
  content: { gap: spacing.md, paddingBottom: spacing.xl, paddingTop: SEARCH_CONTENT_GAP },
  fill: { flexGrow: 1 },
  section: { gap: spacing.xs },
  sectionTitle: { ...textStyles.subheading },
  grid: { flexDirection: "row", flexWrap: "wrap" },
  loading: { alignItems: "center", flexDirection: "row", gap: spacing.sm, paddingVertical: spacing.xl },
  disclaimer: { ...textStyles.caption, color: colors.warning },
});
