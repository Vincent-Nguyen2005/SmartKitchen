import React, { useEffect, useRef, useState } from "react";
import { ActivityIndicator, RefreshControl, ScrollView, StyleSheet, Text, View } from "react-native";
import { CookingPot } from "lucide-react-native";
import { AppText, colors, spacing, textStyles } from "../../theme";
import { useSession } from "../../services/session";
import { createGatewayClient, errorMessage } from "../notifications/gatewayApi";
import { EmptyState } from "../notifications/ui";
import { useCardGrid } from "../../components/ProductCard";
import { useConfirm } from "../../components/ConfirmDialog";
import { dayKey, type MealType } from "../menu/MenuCalendar";
import {
  autoGenerated, generateDay, mealLabels, MenuDishCard, ownDayMenu, removeDish, sortItems,
  type MenuItem, type MenuRecord,
} from "../menu/menuShared";
import { AI_DISCLAIMER, AiDishDetail, type AiDish } from "./AiSuggestions";
import CookingMode from "./CookingMode";
import RecipeDetail from "./RecipeDetail";
import type { Recipe } from "./recipeTypes";

type Props = Readonly<{ accessToken: string | null }>;
const DAY_MEALS: MealType[] = ["BREAKFAST", "LUNCH", "DINNER"];

/**
 * "Nấu ăn": today's menu from Lịch (Bữa sáng, Bữa trưa, Bữa tối, same dishes and order), loaded each time the tab
 * opens so it always matches Lịch; generated once when today has no menu yet. Each card has a round "Đổi món khác"
 * button (the only place to swap); the detail shows the ingredients, steps and "Bắt đầu nấu".
 */
export default function RecipeScreen({ accessToken }: Props): React.JSX.Element {
  const { family } = useSession();
  const familyId = family?.id ?? null;
  const cardGrid = useCardGrid();
  const horizontalPadding = cardGrid.layout.width < 360 ? spacing.lg : spacing.xl;
  const [menu, setMenu] = useState<MenuRecord | null>(null);
  const [recipes, setRecipes] = useState<Recipe[]>([]);
  const [loading, setLoading] = useState(true);
  const [generating, setGenerating] = useState(false);
  const [error, setError] = useState("");
  const [detail, setDetail] = useState<Recipe | null>(null);
  const [aiDetail, setAiDetail] = useState<AiDish | null>(null);
  /** The dish being replaced (spinner on its card / in the detail). */
  const [swappingId, setSwappingId] = useState<string | null>(null);
  const [cooking, setCooking] = useState<Recipe | null>(null);
  const [toast, setToast] = useState<string | null>(null);
  const toastTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const { confirm, dialog } = useConfirm();
  const loadId = useRef(0);
  const api = createGatewayClient(accessToken);
  const todayKey = dayKey(new Date());

  /** Today's menu (generated once when missing) and the active recipes. */
  const load = async (): Promise<void> => {
    if (!accessToken) { setLoading(false); return; }
    const id = ++loadId.current;
    setLoading(true);
    setError("");
    try {
      const [menus, list] = await Promise.all([
        api.get<MenuRecord[]>(`/api/menu?from=${todayKey}&to=${todayKey}`),
        api.get<Recipe[]>("/api/recipes?active=true").catch(() => [] as Recipe[]),
      ]);
      if (id !== loadId.current) return;
      setRecipes(Array.isArray(list) ? list : []);
      let today = ownDayMenu(Array.isArray(menus) ? menus : [], todayKey);
      const key = `${familyId ?? "no-family"}:${todayKey}`;
      if (!today && !autoGenerated.has(key)) {
        autoGenerated.add(key);
        setGenerating(true);
        today = await generateDay(api, todayKey, familyId).finally(() => setGenerating(false));
      }
      if (id === loadId.current) setMenu(today);
    } catch (requestError) {
      if (id === loadId.current) setError(errorMessage(requestError));
    } finally {
      if (id === loadId.current) setLoading(false);
    }
  };

  useEffect(() => {
    void load();
  }, [accessToken, familyId]);

  useEffect(() => () => { if (toastTimer.current) clearTimeout(toastTimer.current); }, []);

  const showToast = (message: string) => {
    setToast(message);
    if (toastTimer.current) clearTimeout(toastTimer.current);
    toastTimer.current = setTimeout(() => setToast(null), 3000);
  };

  const recipeById = new Map(recipes.map((recipe) => [recipe.id, recipe]));
  const items = menu ? sortItems(menu.items) : [];
  const anyAiVisible = items.some((item) => item.details?.ai);

  const closeDetail = () => { setDetail(null); setAiDetail(null); };

  const openDish = (item: MenuItem) => {
    if (item.details?.ai && item.details.aiDish) { setAiDetail(item.details.aiDish); return; }
    const recipe = item.recipeId ? recipeById.get(item.recipeId) : undefined;
    if (recipe) { setDetail(recipe); return; }
    if (item.recipeId) api.get<Recipe>(`/api/recipes/${encodeURIComponent(item.recipeId)}`).then(setDetail).catch((requestError) => setError(errorMessage(requestError)));
  };

  /**
   * "Đổi món khác": in-app confirm, then the server removes the dish and puts one replacement in the same meal and
   * role (Kho-ranked, varied, not recently removed). Feedback: spinner on the card, then a toast with the result.
   */
  const swap = async (item: MenuItem): Promise<boolean> => {
    if (!menu || swappingId) return false;
    const meal = mealLabels[item.mealType].toLocaleLowerCase("vi");
    const ok = await confirm({ title: `Đổi món này sang món khác cho ${meal}?`, message: `${item.dishName} sẽ được thay bằng món khác cùng loại.`, confirmLabel: "Đổi món" });
    if (!ok) return false;
    setSwappingId(item.id);
    try {
      const before = new Set(menu.items.map((entry) => entry.id));
      const result = await removeDish(api, menu.id, item.id);
      setMenu(result);
      const replacement = result.items.find((entry) => entry.mealType === item.mealType && !before.has(entry.id));
      const changed = !!replacement && replacement.dishName.trim().toLocaleLowerCase("vi") !== item.dishName.trim().toLocaleLowerCase("vi");
      showToast(changed ? "Đã đổi món" : "Không tìm được món khác phù hợp cho bữa này");
    } catch (requestError) {
      showToast(errorMessage(requestError));
    } finally {
      setSwappingId(null);
    }
    return true;
  };

  let content: React.ReactNode;
  if ((loading || generating) && !menu) {
    content = (
      <View style={styles.loading}>
        <ActivityIndicator color={colors.primary} />
        <AppText variant="bodySmall" color={colors.muted}>{generating ? "Đang chuẩn bị thực đơn hôm nay" : "Đang tải"}</AppText>
      </View>
    );
  } else if (items.length === 0) {
    content = <EmptyState fill icon={CookingPot} text={error ? "Không tải được thực đơn hôm nay." : "Hôm nay chưa có thực đơn. Mở tab Lịch để tạo."} />;
  } else {
    content = DAY_MEALS.map((meal) => {
      const mealItems = items.filter((item) => item.mealType === meal);
      if (mealItems.length === 0) return null;
      return (
        <View key={meal} style={styles.section}>
          <Text style={styles.sectionTitle} accessibilityRole="header">{mealLabels[meal]}</Text>
          <View onLayout={cardGrid.onLayout} style={[styles.grid, { gap: cardGrid.gap }]}>
            {mealItems.map((item) => (
              <MenuDishCard
                key={item.id}
                item={item}
                recipe={item.recipeId ? recipeById.get(item.recipeId) : undefined}
                width={cardGrid.cardWidth}
                onPress={() => openDish(item)}
                onSwap={() => void swap(item)}
                swapping={swappingId === item.id}
              />
            ))}
          </View>
        </View>
      );
    });
  }

  return (
    <View style={styles.screen}>
      <ScrollView
        showsVerticalScrollIndicator={false}
        showsHorizontalScrollIndicator={false}
        contentContainerStyle={[styles.content, { paddingHorizontal: horizontalPadding }]}
        refreshControl={<RefreshControl refreshing={loading && !!menu} onRefresh={() => void load()} tintColor={colors.primary} />}
      >
        {!!error && <AppText accessibilityRole="alert" variant="bodySmall" color={colors.danger}>{error}</AppText>}
        {anyAiVisible && <Text style={styles.disclaimer}>{AI_DISCLAIMER}</Text>}
        {content}
      </ScrollView>
      <RecipeDetail
        recipe={detail}
        mode="cook"
        onClose={closeDetail}
        onStartCooking={(recipe) => { closeDetail(); setCooking(recipe); }}
      />
      <AiDishDetail
        dish={aiDetail}
        mode="cook"
        onClose={closeDetail}
        onStartCooking={(recipe) => { closeDetail(); setCooking(recipe); }}
      />
      <CookingMode recipe={cooking} onClose={() => setCooking(null)} />
      {dialog}
      {toast && (
        <View pointerEvents="none" style={styles.toastWrap}>
          <Text accessibilityLiveRegion="polite" accessibilityRole="alert" style={styles.toast}>{toast}</Text>
        </View>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  screen: { backgroundColor: colors.background, flex: 1 },
  content: { flexGrow: 1, gap: spacing.md, paddingBottom: spacing.xl, paddingTop: spacing.lg },
  section: { gap: spacing.xs },
  sectionTitle: { ...textStyles.subheading },
  grid: { flexDirection: "row", flexWrap: "wrap" },
  loading: { alignItems: "center", flexDirection: "row", gap: spacing.sm, paddingVertical: spacing.xl },
  disclaimer: { ...textStyles.caption, color: colors.warning },
  toastWrap: { alignItems: "center", bottom: spacing.xl + 64, left: spacing.lg, position: "absolute", right: spacing.lg },
  toast: { ...textStyles.labelSmall, backgroundColor: colors.text, borderRadius: 20, color: colors.surface, overflow: "hidden", paddingHorizontal: spacing.lg, paddingVertical: spacing.md, textAlign: "center" },
});
