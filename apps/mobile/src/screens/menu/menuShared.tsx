import React from "react";
import { Shuffle } from "lucide-react-native";
import { Alert, Platform } from "react-native";
import type { GatewayClient } from "../notifications/gatewayApi";
import { ProductImage } from "../shopping-cart/MarketProducts";
import { CardCaption, cardImageStyle, ImagePlaceholder, ProductCard } from "../../components/ProductCard";
import type { AiDish } from "../recipes/AiSuggestions";
import { minutesText, totalMinutes, type Recipe } from "../recipes/recipeTypes";
import type { MealType } from "./MenuCalendar";

export type PeriodType = "DAY" | "WEEK" | "MONTH";
/** Saved by menu-service with each dish: image, role and, for an AI dish placed in the menu, the dish itself. */
export type DishDetails = { imageUrl?: string | null; role?: string | null; ai?: boolean; aiDish?: AiDish };
export type MenuItem = {
  id: string;
  recipeId?: string | null;
  dishName: string;
  mealType: MealType;
  dayOfWeek: number;
  calories: number | null;
  details?: DishDetails | null;
};
export type MenuRecord = {
  id: string;
  title: string;
  periodType: PeriodType;
  startDate: string;
  endDate: string;
  khoHash?: string | null;
  items: MenuItem[];
};

export const mealLabels: Record<MealType, string> = { BREAKFAST: "Bữa sáng", LUNCH: "Bữa trưa", DINNER: "Bữa tối", SNACK: "Ăn nhẹ" };
const mealOrder: MealType[] = ["BREAKFAST", "LUNCH", "DINNER", "SNACK"];
/** Same order as the server's slots: breakfast dishes then the drink; mặn, canh, rau, xào, tráng miệng. */
const ROLE_ORDER = ["sang", "mot_mon", "man", "canh", "rau", "xao", "trang_mieng", "do_uong"];
const roleRank = (item: MenuItem) => {
  const index = ROLE_ORDER.indexOf(item.details?.role ?? "");
  return index < 0 ? ROLE_ORDER.indexOf("trang_mieng") - 0.5 : index;
};

/** Dishes sorted by meal, then by role (stable, so Lịch and Nấu ăn show the same order). */
export const sortItems = (items: MenuItem[]): MenuItem[] =>
  [...items].sort((left, right) => mealOrder.indexOf(left.mealType) - mealOrder.indexOf(right.mealType) || roleRank(left) - roleRank(right) || left.dishName.localeCompare(right.dishName, "vi"));

export const ownDayMenu = (menus: MenuRecord[], key: string): MenuRecord | null =>
  menus.find((menu) => menu.periodType === "DAY" && menu.startDate.slice(0, 10) === key) ?? null;

/**
 * Days already auto-generated in this app session ("family:YYYY-MM-DD"), shared by Lịch and Nấu ăn. A day's menu
 * is generated once when first opened (today or later), then kept; it never changes by itself.
 */
export const autoGenerated = new Set<string>();

/** Generates (or, explicitly, regenerates) one day's menu from Kho. */
export const generateDay = (api: GatewayClient, key: string, familyId: string | null | undefined): Promise<MenuRecord> =>
  api.post<MenuRecord>("/api/menu/generate", {
    periodType: "DAY",
    startDate: `${key}T00:00:00.000Z`,
    endDate: `${key}T00:00:00.000Z`,
    ...(familyId ? { familyId } : {}),
  });

/** Removes one dish; the server puts one replacement in the same meal and role (or leaves the slot empty). */
export const removeDish = (api: GatewayClient, menuId: string, itemId: string): Promise<MenuRecord> =>
  api.post<MenuRecord>(`/api/menu/${encodeURIComponent(menuId)}/items/${encodeURIComponent(itemId)}/remove`, {});

/** Yes/no confirmation (Alert on phones, window.confirm on web). */
export function confirmAction(title: string, message: string, confirmLabel: string): Promise<boolean> {
  if (Platform.OS === "web") return Promise.resolve(globalThis.confirm?.(`${title}\n${message}`) ?? true);
  return new Promise((resolve) => {
    Alert.alert(title, message, [
      { text: "Hủy", style: "cancel", onPress: () => resolve(false) },
      { text: confirmLabel, style: "destructive", onPress: () => resolve(true) },
    ], { cancelable: true, onDismiss: () => resolve(false) });
  });
}

type CardProps = {
  item: MenuItem;
  recipe?: Recipe;
  width: React.ComponentProps<typeof ProductCard>["width"];
  onPress: () => void;
  /** "minimal": image and name only (Lịch › Theo ngày). */
  variant?: "full" | "minimal";
  /** Nấu ăn: round "Đổi món khác" button on the image; `swapping` shows its spinner. */
  onSwap?: () => void;
  swapping?: boolean;
};

/** A planned dish in the shared card style: image, name, kcal, total time; AI dishes carry the "AI" pill. */
export function MenuDishCard({ item, recipe, width, onPress, variant = "full", onSwap, swapping = false }: CardProps): React.JSX.Element {
  const aiDish = item.details?.ai ? item.details.aiDish : undefined;
  const minutes = recipe ? totalMinutes(recipe) : aiDish ? aiDish.totalMinutes : null;
  const kcal = item.calories == null ? "-- kcal" : `${Math.round(item.calories)} kcal`;
  return (
    <ProductCard
      width={width}
      accessibilityLabel={`${mealLabels[item.mealType]}: ${item.dishName}, ${kcal}${minutes !== null ? `, ${minutesText(minutes)}` : ""}${aiDish ? ", món AI gợi ý" : ""}. Mở công thức`}
      onPress={onPress}
      image={aiDish ? <ImagePlaceholder /> : <ProductImage uri={recipe?.imageUrl ?? item.details?.imageUrl ?? null} style={cardImageStyle} />}
      pill={aiDish ? { label: "AI", tone: "ai" } : null}
      name={item.dishName}
      subtitle={variant === "full" ? kcal : undefined}
      footer={variant === "full" && minutes !== null ? <CardCaption text={minutesText(minutes)} /> : undefined}
      cornerAction={onSwap ? { icon: Shuffle, label: "Đổi món khác", onPress: onSwap, busy: swapping } : undefined}
    />
  );
}
