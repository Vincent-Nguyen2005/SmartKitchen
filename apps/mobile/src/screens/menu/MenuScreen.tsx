import React, { useEffect, useRef, useState } from "react";
import {
  ActivityIndicator,
  AppState,
  Pressable,
  RefreshControl,
  ScrollView,
  StyleSheet,
  Text,
  View,
  useWindowDimensions,
  type ScrollViewInstance,
} from "react-native";
import { ChevronLeft, ChevronRight, RefreshCw } from "lucide-react-native";
import { AppIcon, AppText, breakpoints, colors, radius, spacing, textStyles, touchTarget } from "../../theme";
import { createGatewayClient, errorMessage } from "../notifications/gatewayApi";
import { useCardGrid } from "../../components/ProductCard";
import { useConfirm } from "../../components/ConfirmDialog";
import { SegmentTabs } from "../../components/SegmentTabs";
import RecipeDetail from "../recipes/RecipeDetail";
import { AiDishDetail, type AiDish } from "../recipes/AiSuggestions";
import { dishServings, menuPeople, scaleRecipe } from "../recipes/portions";
import { useSession } from "../../services/session";
import { canRebuildWeek, WEEK_REBUILD_CONFIRM, weekRebuildDays } from "./weekRebuild";
import type { Recipe } from "../recipes/recipeTypes";
import { addDays, dayKey, keyToDate, monthGridDays, MonthCalendar, startOfWeek, weekday, WeekTimetable, type MealType } from "./MenuCalendar";
import {
  autoGenerated, detailHealth, generateDay, mealLabels, MenuDishCard, ownDayMenu, sortItems,
  type MenuItem, type MenuRecord, type PeriodType,
} from "./menuShared";

type Props = Readonly<{
  accessToken: string | null;
  familyId?: string | null;
  /** Open today's day view on this meal (greeting card in Thông báo, "Chào buổi sáng" push); a new key re-opens. */
  focusMeal?: { meal: MealType; key: number } | null;
}>;

const periods: Array<{ value: PeriodType; label: string }> = [
  { value: "DAY", label: "Theo ngày" },
  { value: "WEEK", label: "Theo tuần" },
  { value: "MONTH", label: "Theo tháng" },
];
const stepLabels: Record<PeriodType, { back: string; next: string; backA11y: string; nextA11y: string }> = {
  DAY: { back: "Hôm trước", next: "Hôm sau", backA11y: "Ngày trước", nextA11y: "Ngày sau" },
  WEEK: { back: "Tuần trước", next: "Tuần sau", backA11y: "Tuần trước", nextA11y: "Tuần sau" },
  MONTH: { back: "Tháng trước", next: "Tháng sau", backA11y: "Tháng trước", nextA11y: "Tháng sau" },
};
const DAY_MEALS: MealType[] = ["BREAKFAST", "LUNCH", "DINNER"];

/** Weeks already filled in this app session (one try each). */
const weeksFilled = new Set<string>();

const pad = (value: number) => String(value).padStart(2, "0");
const formatDay = (date: Date) => `${pad(date.getDate())}/${pad(date.getMonth() + 1)}/${date.getFullYear()}`;

/** First and last day (YYYY-MM-DD) the current view shows: one menu request covers all of it. */
function viewRange(period: PeriodType, date: Date): { from: string; to: string } {
  if (period === "DAY") return { from: dayKey(date), to: dayKey(date) };
  if (period === "WEEK") return { from: dayKey(startOfWeek(date)), to: dayKey(addDays(startOfWeek(date), 6)) };
  const days = monthGridDays(date);
  return { from: dayKey(days[0]), to: dayKey(days[days.length - 1]) };
}

function shiftPeriod(date: Date, period: PeriodType, direction: -1 | 1): Date {
  if (period === "DAY") return addDays(date, direction);
  if (period === "WEEK") return addDays(date, direction * 7);
  const target = new Date(date.getFullYear(), date.getMonth() + direction, 1);
  const lastDay = new Date(target.getFullYear(), target.getMonth() + 1, 0).getDate();
  return new Date(target.getFullYear(), target.getMonth(), Math.min(date.getDate(), lastDay));
}

/**
 * Dishes planned for a day: the day's own menu first, otherwise a week/month menu that covers the day
 * (those store a weekday). Sorted by meal and role.
 */
function itemsForDay(menus: MenuRecord[], key: string): MenuItem[] {
  const own = ownDayMenu(menus, key);
  if (own) return sortItems(own.items);
  const covering = menus.find((menu) => menu.periodType !== "DAY" && menu.startDate.slice(0, 10) <= key && menu.endDate.slice(0, 10) >= key);
  if (!covering) return [];
  const day = weekday(keyToDate(key));
  return sortItems(covering.items.filter((item) => item.dayOfWeek === day));
}

/**
 * "Lịch": the family's meal calendar. A day's menu (today or a future day) is generated once when first opened
 * and then kept as saved; it never changes by itself. Dishes open read-only here ("Đổi món khác" is in Nấu ăn);
 * "Làm mới theo kho" regenerates the whole day after a confirmation. Past days are read-only.
 */
export default function MenuScreen({ accessToken, familyId, focusMeal }: Props): React.JSX.Element {
  const { width } = useWindowDimensions();
  const isWide = width >= breakpoints.wide;
  const horizontalPadding = width < 360 ? spacing.sm : isWide ? spacing.xl : spacing.lg;
  const cardGrid = useCardGrid();
  const [period, setPeriod] = useState<PeriodType>("DAY");
  const [selectedDate, setSelectedDate] = useState(() => new Date());
  const [followToday, setFollowToday] = useState(true);
  const [menus, setMenus] = useState<MenuRecord[]>([]);
  const [recipes, setRecipes] = useState<Map<string, Recipe>>(new Map());
  const [loading, setLoading] = useState(true);
  const [loadFailed, setLoadFailed] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [toast, setToast] = useState<string | null>(null);
  const [detail, setDetail] = useState<Recipe | null>(null);
  const [aiDetail, setAiDetail] = useState<AiDish | null>(null);
  /** The planned dish whose detail is open (its health warnings and alternative). */
  const [openedItem, setOpenedItem] = useState<MenuItem | null>(null);
  const sessionFamily = useSession().family;
  const memberCount = sessionFamily?.members.length;
  const toastTimer = useRef<ReturnType<typeof setTimeout> | null>(null);
  const { confirm, dialog } = useConfirm();
  const loadId = useRef(0);
  const api = createGatewayClient(accessToken);
  const { from, to } = viewRange(period, selectedDate);
  const todayKey = dayKey(new Date());
  const selectedKey = dayKey(selectedDate);
  const isPast = selectedKey < todayKey;
  // Scrolling to a focused meal: the meals block is a direct child of the ScrollView content.
  const scrollRef = useRef<ScrollViewInstance>(null);
  const mealsY = useRef<number | null>(null);
  const sectionY = useRef(new Map<MealType, number>());
  const pendingMeal = useRef<MealType | null>(null);
  const scrollToPendingMeal = () => {
    const meal = pendingMeal.current;
    const offset = meal ? sectionY.current.get(meal) : undefined;
    if (!meal || offset === undefined || mealsY.current === null) return;
    pendingMeal.current = null;
    scrollRef.current?.scrollTo({ y: Math.max(0, mealsY.current + offset - spacing.sm), animated: true });
  };
  useEffect(() => {
    if (!focusMeal) return;
    setPeriod("DAY");
    setSelectedDate(new Date());
    setFollowToday(true);
    pendingMeal.current = focusMeal.meal;
    scrollToPendingMeal();
  }, [focusMeal?.key]);

  useEffect(() => () => { if (toastTimer.current) clearTimeout(toastTimer.current); }, []);

  const showToast = (message: string) => {
    setToast(message);
    if (toastTimer.current) clearTimeout(toastTimer.current);
    toastTimer.current = setTimeout(() => setToast(null), 2500);
  };

  /** Menus overlapping the shown day / week / month grid, in one request. */
  const loadMenus = async (): Promise<void> => {
    if (!accessToken) {
      setMenus([]);
      setLoading(false);
      return;
    }
    const id = ++loadId.current;
    setLoading(true);
    setError("");
    try {
      const result = await api.get<MenuRecord[] | { items: MenuRecord[] }>(`/api/menu?from=${from}&to=${to}`);
      if (id !== loadId.current) return;
      setMenus(Array.isArray(result) ? result : result.items);
      setLoadFailed(false);
    } catch (requestError) {
      if (id !== loadId.current) return;
      setError(errorMessage(requestError));
      setLoadFailed(true);
    } finally {
      if (id === loadId.current) setLoading(false);
    }
  };

  useEffect(() => {
    void loadMenus();
  }, [accessToken, from, to]);

  // Active recipes (image, total time, steps) for the dish cards and the detail screen.
  useEffect(() => {
    if (!accessToken) return;
    let active = true;
    api.get<Recipe[]>("/api/recipes?active=true")
      .then((list) => { if (active && Array.isArray(list)) setRecipes(new Map(list.map((recipe) => [recipe.id, recipe]))); })
      .catch(() => undefined);
    return () => { active = false; };
  }, [accessToken]);

  useEffect(() => {
    if (!followToday) return;
    const timer = setInterval(() => setSelectedDate(new Date()), 60_000);
    const subscription = AppState.addEventListener("change", (state) => {
      if (state === "active") setSelectedDate(new Date());
    });
    return () => { clearInterval(timer); subscription.remove(); };
  }, [followToday]);

  const replaceMenu = (result: MenuRecord) =>
    setMenus((current) => [
      result,
      ...current.filter((entry) => entry.id !== result.id && !(entry.periodType === "DAY" && entry.startDate.slice(0, 10) === result.startDate.slice(0, 10))),
    ]);

  /** Generates the selected day's menu from Kho (first open, or the explicit "Làm mới theo kho"). */
  const generate = async (announce: boolean): Promise<void> => {
    if (!accessToken || busy || isPast) return;
    setBusy(true);
    setError("");
    try {
      replaceMenu(await generateDay(api, selectedKey, familyId));
      if (announce) showToast("Đã tạo lại thực đơn theo Kho");
    } catch (requestError) {
      setError(errorMessage(requestError));
    } finally {
      setBusy(false);
    }
  };

  const regenerateDay = async () => {
    const title = selectedKey === todayKey ? "Tạo lại toàn bộ thực đơn hôm nay?" : `Tạo lại toàn bộ thực đơn ngày ${formatDay(selectedDate).slice(0, 5)}?`;
    if (await confirm({ title, message: "Tất cả món của ngày này sẽ được gợi ý lại theo Kho.", confirmLabel: "Tạo lại" })) void generate(true);
  };

  const closeDetail = () => { setDetail(null); setAiDetail(null); setOpenedItem(null); };

  const menuOf = (item: MenuItem | null) => menus.find((menu) => menu.items.some((entry) => entry.id === item?.id));
  /** People a planned dish is cooked for ("cho N người"): its menu's servings, else the current family size, else 1. */
  const peopleFor = (item: MenuItem | null): number => menuPeople(menuOf(item)?.servings, memberCount);
  /** Planned portions of the dish ("N phần"): what its amounts are scaled to. */
  const servingsFor = (item: MenuItem | null): number => dishServings(item?.details, menuOf(item)?.servings, memberCount);

  /** The alternative of an unsuitable dish (view-only here, like every dish in Lịch). */
  const openRecipe = async (recipeId: string): Promise<void> => {
    const people = peopleFor(openedItem);
    const portions = servingsFor(openedItem);
    const known = recipes.get(recipeId);
    if (known) { setDetail(scaleRecipe(known, portions, people)); return; }
    try {
      setDetail(scaleRecipe(await api.get<Recipe>(`/api/recipes/${encodeURIComponent(recipeId)}`), portions, people));
    } catch (requestError) {
      showToast(errorMessage(requestError));
    }
  };

  /** Opens the shared detail (view-only from Lịch): an AI dish (with its actions) or the recipe (loaded by id when not in the list). */
  const openDish = async (item: MenuItem): Promise<void> => {
    setOpenedItem(item);
    if (item.details?.ai && item.details.aiDish) { setAiDetail(item.details.aiDish); return; }
    if (!item.recipeId) { showToast("Món này chưa có công thức."); return; }
    // Quantities for the dish's planned portions ("N phần"); the label stays the family ("cho N người").
    const people = peopleFor(item);
    const portions = servingsFor(item);
    const known = recipes.get(item.recipeId);
    if (known) { setDetail(scaleRecipe(known, portions, people)); return; }
    try {
      setDetail(scaleRecipe(await api.get<Recipe>(`/api/recipes/${encodeURIComponent(item.recipeId)}`), portions, people));
    } catch (requestError) {
      showToast(errorMessage(requestError));
    }
  };

  const openDay = (key: string) => {
    setPeriod("DAY");
    setSelectedDate(keyToDate(key));
    setFollowToday(key === todayKey);
  };

  const dayItems = itemsForDay(menus, selectedKey);
  const dayMenu = ownDayMenu(menus, selectedKey);

  // Today or a future day with no menu yet: generate it once (per family and day), then it stays as saved.
  useEffect(() => {
    if (period !== "DAY" || isPast || loading || loadFailed || busy || dayItems.length > 0 || !accessToken) return;
    const key = `${familyId ?? "no-family"}:${selectedKey}`;
    if (autoGenerated.has(key)) return;
    autoGenerated.add(key);
    void generate(false);
  }, [period, isPast, loading, loadFailed, busy, dayItems.length, accessToken, familyId, selectedKey]);

  /** "Tạo lại tuần" (family owner): today and the later days of the shown week, with the calorie-based planner. */
  const rebuildDays = weekRebuildDays(from, todayKey);
  const rebuildWeek = async () => {
    if (!accessToken || busy || rebuildDays.length === 0 || !(await confirm({ ...WEEK_REBUILD_CONFIRM }))) return;
    setBusy(true);
    setError("");
    try {
      const created = await api.post<MenuRecord[]>("/api/menu/generate-days", { days: rebuildDays, replace: true, ...(familyId ? { familyId } : {}) });
      const replaced = new Set(created.map((menu) => menu.startDate.slice(0, 10)));
      setMenus((current) => [...created, ...current.filter((menu) => !(menu.periodType === "DAY" && replaced.has(menu.startDate.slice(0, 10))))]);
      showToast("Đã tạo lại thực đơn cả tuần");
    } catch (requestError) {
      setError(errorMessage(requestError));
    } finally {
      setBusy(false);
    }
  };

  // Theo tuần: today and the later days of the shown week that have no menu are generated in one request.
  useEffect(() => {
    if (period !== "WEEK" || loading || loadFailed || !accessToken) return;
    const weekKey = `${familyId ?? "no-family"}:${from}`;
    if (weeksFilled.has(weekKey)) return;
    const days = Array.from({ length: 7 }, (_, index) => dayKey(addDays(keyToDate(from), index)))
      .filter((key) => key >= todayKey && itemsForDay(menus, key).length === 0);
    if (days.length === 0) return;
    weeksFilled.add(weekKey);
    setBusy(true);
    api.post<MenuRecord[]>("/api/menu/generate-days", { days, ...(familyId ? { familyId } : {}) })
      .then((created) => setMenus((current) => [...created, ...current]))
      .catch((requestError) => setError(errorMessage(requestError)))
      .finally(() => setBusy(false));
  }, [period, loading, loadFailed, accessToken, familyId, from, todayKey]);

  const rangeLabel = period === "DAY"
    ? formatDay(selectedDate)
    : period === "WEEK"
      ? `${formatDay(keyToDate(from)).slice(0, 5)} – ${formatDay(keyToDate(to))}`
      : `Tháng ${selectedDate.getMonth() + 1}/${selectedDate.getFullYear()}`;
  const steps = stepLabels[period];

  const dishesFor = (key: string) => itemsForDay(menus, key);
  let scheduleContent: React.ReactNode;
  if (loading && menus.length === 0 && !(period === "DAY" && busy)) {
    scheduleContent = (
      <View style={styles.loading}>
        <ActivityIndicator color={colors.primary} />
        <AppText variant="bodySmall" color={colors.muted}>Đang tải thực đơn</AppText>
      </View>
    );
  } else if (period === "WEEK") {
    scheduleContent = (
      <View style={styles.meals}>
        {busy && <Text style={styles.muted}>Đang chuẩn bị thực đơn cho các ngày còn lại...</Text>}
        <WeekTimetable weekStart={keyToDate(from)} todayKey={todayKey} dishesFor={dishesFor} onOpenDay={openDay} />
      </View>
    );
  } else if (period === "MONTH") {
    scheduleContent = <MonthCalendar anchor={selectedDate} todayKey={todayKey} dishesFor={dishesFor} onOpenDay={openDay} />;
  } else if (busy && dayItems.length === 0) {
    scheduleContent = (
      <View style={styles.loading}>
        <ActivityIndicator color={colors.primary} />
        <AppText variant="bodySmall" color={colors.muted}>Đang gợi ý món theo Kho</AppText>
      </View>
    );
  } else if (dayItems.length === 0) {
    scheduleContent = <Text style={styles.muted}>{isPast ? "Ngày này không có thực đơn." : "Chưa có thực đơn cho ngày này."}</Text>;
  } else {
    const meals = dayItems.some((item) => item.mealType === "SNACK") ? [...DAY_MEALS, "SNACK" as MealType] : DAY_MEALS;
    scheduleContent = (
      <View style={styles.meals} onLayout={(event) => { mealsY.current = event.nativeEvent.layout.y; scrollToPendingMeal(); }}>
        {meals.map((meal) => {
          const items = dayItems.filter((item) => item.mealType === meal);
          if (items.length === 0 && meal === "SNACK") return null;
          const kcal = items.reduce((sum, item) => sum + (item.calories ?? 0), 0);
          return (
            <View key={meal} style={styles.mealSection} onLayout={(event) => { sectionY.current.set(meal, event.nativeEvent.layout.y); scrollToPendingMeal(); }}>
              <View style={styles.mealHeader}>
                <Text style={styles.mealTitle} accessibilityRole="header">{mealLabels[meal]}</Text>
                {kcal > 0 && <Text style={styles.mealKcal}>{Math.round(kcal)} kcal</Text>}
              </View>
              {items.length === 0 ? (
                <Text style={styles.muted}>Chưa có món</Text>
              ) : (
                <View onLayout={cardGrid.onLayout} style={[styles.grid, { gap: cardGrid.gap }]}>
                  {items.map((item) => (
                    <MenuDishCard
                      key={item.id}
                      item={item}
                      recipe={item.recipeId ? recipes.get(item.recipeId) : undefined}
                      width={cardGrid.cardWidth}
                      variant="minimal"
                      portions={servingsFor(item)}
                      onPress={() => void openDish(item)}
                    />
                  ))}
                </View>
              )}
            </View>
          );
        })}
      </View>
    );
  }

  return (
    <View style={styles.screen}>
      <ScrollView ref={scrollRef} showsVerticalScrollIndicator={false} showsHorizontalScrollIndicator={false}
        contentContainerStyle={[styles.content, { maxWidth: isWide ? breakpoints.extraWide : undefined, paddingHorizontal: horizontalPadding }]}
        refreshControl={<RefreshControl refreshing={loading && menus.length > 0} onRefresh={() => void loadMenus()} tintColor={colors.primary} />}
      >
        <SegmentTabs<PeriodType> options={periods} value={period} onChange={setPeriod} />

        <View style={styles.periodNavigation}>
          <Pressable accessibilityRole="button" accessibilityLabel={steps.backA11y} onPress={() => { setFollowToday(false); setSelectedDate((date) => shiftPeriod(date, period, -1)); }} style={styles.navigationButton}>
            <AppIcon icon={ChevronLeft} size="sm" color={colors.primary} />
            <AppText variant="labelSmall" color={colors.primary}>{steps.back}</AppText>
          </Pressable>
          <Pressable accessibilityRole="button" accessibilityLabel={`Đang xem ${rangeLabel}. Về hôm nay`} onPress={() => { setSelectedDate(new Date()); setFollowToday(true); }} style={styles.rangeButton}>
            <AppText variant="labelSmall" color={colors.text} style={styles.rangeText}>{rangeLabel}</AppText>
          </Pressable>
          <Pressable accessibilityRole="button" accessibilityLabel={steps.nextA11y} onPress={() => { setFollowToday(false); setSelectedDate((date) => shiftPeriod(date, period, 1)); }} style={styles.navigationButton}>
            <AppText variant="labelSmall" color={colors.primary}>{steps.next}</AppText>
            <AppIcon icon={ChevronRight} size="sm" color={colors.primary} />
          </Pressable>
          {period === "DAY" && !isPast && (
            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Làm mới theo kho: tạo lại toàn bộ thực đơn của ngày này"
              accessibilityState={{ busy, disabled: !accessToken || busy }}
              disabled={!accessToken || busy}
              onPress={() => void regenerateDay()}
              style={[styles.refreshButton, (!accessToken || busy) && styles.disabled]}
            >
              {busy ? <ActivityIndicator color={colors.primary} /> : <AppIcon icon={RefreshCw} size="sm" color={colors.primary} />}
            </Pressable>
          )}
          {period === "WEEK" && rebuildDays.length > 0 && canRebuildWeek(sessionFamily) && (
            <Pressable
              accessibilityRole="button"
              accessibilityLabel="Tạo lại tuần: gợi ý lại thực đơn từ hôm nay đến hết tuần"
              accessibilityState={{ busy, disabled: !accessToken || busy }}
              disabled={!accessToken || busy}
              onPress={() => void rebuildWeek()}
              style={[styles.refreshButton, (!accessToken || busy) && styles.disabled]}
            >
              {busy ? <ActivityIndicator color={colors.primary} /> : <AppIcon icon={RefreshCw} size="sm" color={colors.primary} />}
            </Pressable>
          )}
        </View>

        {!!error && <AppText accessibilityRole="alert" variant="bodySmall" color={colors.danger} style={styles.message}>{error}</AppText>}
        {period === "DAY" && dayMenu?.healthUnavailable && (
          <AppText variant="bodySmall" color={colors.warning} style={styles.message}>Chưa tải được thông tin dị ứng của gia đình, hãy làm mới sau</AppText>
        )}
        {scheduleContent}
      </ScrollView>
      {/* Lịch shows dishes read-only; steps, cooking and "Đổi món khác" live in Nấu ăn. */}
      <RecipeDetail recipe={detail} onClose={closeDetail} mode="view" health={detailHealth(openedItem, detail?.id, (id) => void openRecipe(id))} />
      <AiDishDetail dish={aiDetail} onClose={closeDetail} mode="view" people={peopleFor(openedItem)} portions={servingsFor(openedItem)} />
      {dialog}
      {toast && (
        <View pointerEvents="none" style={styles.toastWrap}>
          <Text accessibilityLiveRegion="polite" accessibilityRole="alert" style={styles.toast}>{toast}</Text>
        </View>
      )}
    </View>
  );
}

const styles = StyleSheet.create({
  screen: { backgroundColor: colors.background, flex: 1 },
  content: { alignSelf: "center", backgroundColor: colors.background, flexGrow: 1, paddingBottom: spacing.xl, paddingTop: spacing.lg, width: "100%" },
  periodNavigation: { alignItems: "center", flexDirection: "row", gap: spacing.xs, marginBottom: spacing.md },
  navigationButton: { alignItems: "center", flexDirection: "row", gap: spacing.xs, justifyContent: "center", minHeight: touchTarget, minWidth: 62 },
  rangeButton: { alignItems: "center", flex: 1, justifyContent: "center", minHeight: touchTarget, paddingHorizontal: spacing.xs },
  rangeText: { textAlign: "center" },
  refreshButton: { alignItems: "center", backgroundColor: colors.primarySoft, borderRadius: radius.pill, height: touchTarget, justifyContent: "center", width: touchTarget },
  disabled: { opacity: 0.55 },
  message: { marginBottom: spacing.md },
  loading: { alignItems: "center", flexDirection: "row", gap: spacing.sm, paddingVertical: spacing.xl },
  meals: { gap: spacing.md },
  mealSection: { gap: spacing.xs },
  mealHeader: { alignItems: "baseline", flexDirection: "row", gap: spacing.sm, justifyContent: "space-between" },
  mealTitle: { ...textStyles.subheading },
  mealKcal: { ...textStyles.labelSmall, color: colors.primary },
  muted: { ...textStyles.bodySmall, color: colors.muted },
  grid: { flexDirection: "row", flexWrap: "wrap" },
  toastWrap: { alignItems: "center", bottom: spacing.xl + 64, left: spacing.lg, position: "absolute", right: spacing.lg },
  toast: { ...textStyles.labelSmall, backgroundColor: colors.text, borderRadius: 20, color: colors.surface, overflow: "hidden", paddingHorizontal: spacing.lg, paddingVertical: spacing.md },
});
